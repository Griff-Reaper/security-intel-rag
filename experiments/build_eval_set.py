"""
Build a committed evaluation set of paraphrased questions.

Every retrieval number this project has published so far used queries taken from
the corpus itself: a CVE's own identifier, its product strings, or the opening
sentence of its own description. That last one is labelled a control precisely
because it is not an evaluation - the query is copied out of the answer, so it
rewards exact string matching and tells you almost nothing about whether
embeddings understand anything.

This script builds the missing thing: for each CVE in the pinned sample, a
question phrased the way an analyst would ask it, generated by Claude from the
description with instructions to paraphrase rather than quote.

    python experiments/build_eval_set.py            # generate (resumable)
    python experiments/build_eval_set.py --report   # leakage stats only

Writes experiments/samples/paraphrased_eval.json, which is committed. The
generation costs money and is not reproducible token-for-token, so the *output*
is the artifact, not the run.

Three honesty problems with generating an eval set this way, all of them
measured or stated rather than hoped away:

1. Vocabulary leakage. A model asked to paraphrase a description will still
   reuse some of its words, and every reused rare word hands the lexical arm a
   free hit. The overlap is therefore measured against the copied-sentence
   control in the same script, so "less leaky than the control" is a number
   rather than a claim. Leakage is reported, not eliminated - it cannot be.

2. Generator bias. These are questions a language model believes an analyst
   would ask, which is not the same as questions analysts do ask. A set written
   by working analysts would be better and is not available here.

3. Unanswerable items. Plenty of CVE descriptions are too thin to support any
   distinctive question ("Unspecified vulnerability in ..."). Those are kept and
   flagged rather than quietly dropped, because dropping them would inflate
   every score by removing exactly the records that are hard to retrieve.

The eval set reuses the pinned identifier sample deliberately. Same 200 CVEs,
different queries, so "dense scores 0.122 on product+version and X on
paraphrased questions" is a statement about one fixed set of documents rather
than a comparison across two different draws.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Set

import chromadb
from chromadb.config import Settings
from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT / "src"))

import claude_client  # noqa: E402
import provenance  # noqa: E402

SAMPLE_PATH = PROJECT_ROOT / "experiments" / "samples" / "identifier_sample.json"
OUTPUT_PATH = PROJECT_ROOT / "experiments" / "samples" / "paraphrased_eval.json"

DEFAULT_MODEL = "claude-opus-5"
MAX_TOKENS = 600
SENTENCE_MAX = 240

# Words too common to count as leakage; their presence in both a question and a
# document says nothing about copying.
STOPWORDS: Set[str] = {
    "a", "an", "the", "and", "or", "but", "if", "then", "than", "that", "this",
    "these", "those", "is", "are", "was", "were", "be", "been", "being", "to",
    "of", "in", "on", "at", "by", "for", "with", "from", "as", "it", "its",
    "can", "could", "may", "might", "will", "would", "there", "when", "which",
    "who", "what", "how", "why", "not", "no", "all", "any", "some", "via",
    "allows", "allow", "attacker", "vulnerability", "vulnerabilities", "issue",
    "affected", "affects", "versions", "version", "prior", "before", "after",
    "remote", "local", "user", "users", "s",
}

PROMPT = """You are building an evaluation set for a vulnerability search system.

Below is the description of a single CVE. Write the question a security analyst \
would actually type into a search box when they are trying to find this \
vulnerability but do not already know which CVE it is.

Rules:
- Do NOT include any CVE identifier.
- Do NOT copy distinctive phrases from the description. Rephrase in your own \
words. Reusing an unusual product name is acceptable only if an analyst \
searching for this issue would plausibly know it.
- Write one natural question, 8-25 words, no preamble.
- If the description is too vague or generic to support any distinctive \
question, set "specific" to false and still write the best question you can.

Description:
{description}

Respond with only a JSON object:
{{"question": "...", "specific": true or false}}"""


def tokenize(text: str) -> Set[str]:
    """Content words, lowercased, for the leakage measurement."""
    words = re.findall(r"[A-Za-z][A-Za-z0-9._-]{2,}", text.lower())
    return {w for w in words if w not in STOPWORDS}


def leakage(query: str, document: str) -> float:
    """
    Share of the query's content words that also appear in the target document.

    The overlap coefficient rather than Jaccard: document length varies by an
    order of magnitude across the corpus, and Jaccard would mostly measure that
    instead of measuring copying.
    """
    q, d = tokenize(query), tokenize(document)
    return len(q & d) / len(q) if q else 0.0


def first_sentence(document: str) -> str:
    """The Phase 2 control query, rebuilt here for the leakage comparison."""
    body = document.split(": ", 1)[-1]
    cut = body.find(". ")
    return body[: cut + 1] if 0 < cut < SENTENCE_MAX else body[:SENTENCE_MAX]


def description_of(document: str) -> str:
    """The description portion of a stored document, without the metadata lines."""
    body = document.split(": ", 1)[-1]
    return body.split("\n\n", 1)[0].strip()


def load_excluded() -> Dict[str, str]:
    """CVEs a previous run could not generate a question for, and why."""
    if not OUTPUT_PATH.exists():
        return {}
    return json.loads(OUTPUT_PATH.read_text(encoding="utf-8")).get("excluded", {})


def load_existing() -> Dict[str, Dict[str, Any]]:
    """Previously generated items, so a run can resume after an interruption."""
    if not OUTPUT_PATH.exists():
        return {}
    payload = json.loads(OUTPUT_PATH.read_text(encoding="utf-8"))
    return {item["cve_id"]: item for item in payload.get("items", [])}


def generate_one(client, model: str, description: str, attempts: int = 3) -> Dict[str, Any]:
    """
    One question, or a reason it could not be produced.

    Returns {"ok": True, "question": ..., "specific": ...} or
    {"ok": False, "reason": "refusal" | "unparseable" | "error: ..."}.

    Refusals are distinguished from parse failures because they mean different
    things for the eval set. A parse failure is a bug worth retrying; a refusal
    is the safety classifier declining a particular *kind* of vulnerability
    description, which removes those CVEs from the set non-randomly and has to
    be reported rather than counted as noise.
    """
    last_error = ""
    for attempt in range(attempts):
        try:
            response = client.messages.create(
                model=model,
                max_tokens=MAX_TOKENS,
                messages=[
                    {"role": "user", "content": PROMPT.format(description=description)}
                ],
            )
        except Exception as exc:  # noqa: BLE001 - transient SDK/transport failures
            last_error = f"{type(exc).__name__}: {exc}"
            time.sleep(1.5 * (attempt + 1))
            continue

        # Safety classifiers can decline: HTTP 200, stop_reason "refusal", and
        # content that must not be indexed into. Retrying will not help.
        if response.stop_reason == "refusal":
            return {"ok": False, "reason": "refusal"}

        text = next((b.text for b in response.content if b.type == "text"), "")
        match = re.search(r"\{.*\}", text, re.DOTALL)
        if match:
            try:
                parsed = json.loads(match.group(0))
                question = (parsed.get("question") or "").strip()
                if question:
                    return {
                        "ok": True,
                        "question": question,
                        "specific": bool(parsed.get("specific", True)),
                    }
            except json.JSONDecodeError:
                pass
        last_error = "unparseable"

    return {"ok": False, "reason": last_error or "unparseable"}


def write_output(items: List[Dict[str, Any]], model: str, stats: Dict[str, Any],
                 excluded: Optional[Dict[str, str]] = None) -> None:
    payload = {
        **provenance.stamp(),
        "purpose": "paraphrased retrieval evaluation; questions are generated, "
                   "not copied from the documents",
        "generator_model": model,
        "sample_source": str(SAMPLE_PATH.relative_to(PROJECT_ROOT)),
        "caveats": [
            "Questions are what a language model believes an analyst would ask, "
            "not questions collected from analysts.",
            "Paraphrasing reduces but cannot eliminate vocabulary overlap with "
            "the target document; the overlap is measured below.",
            "Items flagged specific=false are kept, because dropping the CVEs "
            "with uninformative descriptions would inflate every score.",
        ],
        "leakage": stats,
        # CVEs from the pinned sample that produced no question, and why. Kept
        # in the artifact because their absence is not random: the safety
        # classifier declines particular kinds of vulnerability description, so
        # the eval set under-represents them and any score computed over it is
        # a score over the remainder.
        "excluded": excluded or {},
        "items": items,
    }
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def leakage_stats(items: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Compare paraphrased-question leakage against the copied-sentence control."""
    paraphrased = [i["leakage_vs_target"] for i in items]
    control = [i["control_leakage_vs_target"] for i in items]

    def summary(values: List[float]) -> Dict[str, float]:
        ordered = sorted(values)
        n = len(ordered)
        return {
            "n": n,
            "mean": round(sum(ordered) / n, 4) if n else 0.0,
            "median": round(ordered[n // 2], 4) if n else 0.0,
            "p90": round(ordered[min(n - 1, int(0.9 * n))], 4) if n else 0.0,
        }

    return {
        "metric": "share of query content words also present in the target document",
        "paraphrased_question": summary(paraphrased),
        "copied_sentence_control": summary(control),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--persist-dir", default=str(PROJECT_ROOT / "chroma_db"))
    parser.add_argument("--collection", default="nvd_cve")
    parser.add_argument("--model", default=os.getenv("CLAUDE_MODEL", DEFAULT_MODEL))
    parser.add_argument("--limit", type=int, help="generate at most this many (for a trial)")
    parser.add_argument("--report", action="store_true",
                        help="recompute leakage stats from the existing file and exit")
    args = parser.parse_args()

    load_dotenv()
    provenance.require_layout_match()

    client_db = chromadb.PersistentClient(
        path=args.persist_dir, settings=Settings(anonymized_telemetry=False)
    )
    collection = client_db.get_collection(args.collection)

    sample_ids = json.loads(SAMPLE_PATH.read_text(encoding="utf-8"))["cve_ids"]
    records = collection.get(ids=sample_ids, include=["documents"])
    documents = dict(zip(records["ids"], records["documents"]))

    existing = load_existing()

    if args.report:
        items = [existing[c] for c in sample_ids if c in existing]
        stats = leakage_stats(items)
        print(json.dumps(stats, indent=2))
        return

    try:
        client = claude_client.build_client()
    except (claude_client.UnsupportedSDKError, ValueError) as exc:
        raise SystemExit(str(exc)) from exc

    todo = [c for c in sample_ids if c not in existing][: args.limit or None]
    print(f"pinned sample: {len(sample_ids)} CVEs | already generated: "
          f"{len(existing)} | to generate: {len(todo)}")

    excluded: Dict[str, str] = dict(load_excluded())
    for index, cve_id in enumerate(todo, start=1):
        document = documents.get(cve_id)
        if not document:
            continue
        description = description_of(document)
        generated = generate_one(client, args.model, description)
        if not generated["ok"]:
            excluded[cve_id] = generated["reason"]
            print(f"  [{index}/{len(todo)}] {cve_id}: {generated['reason']}")
            continue
        excluded.pop(cve_id, None)

        control = first_sentence(document)
        existing[cve_id] = {
            "cve_id": cve_id,
            "question": generated["question"],
            "specific": generated["specific"],
            "leakage_vs_target": round(leakage(generated["question"], document), 4),
            "control_leakage_vs_target": round(leakage(control, document), 4),
        }
        if index % 10 == 0 or index == len(todo):
            ordered = [existing[c] for c in sample_ids if c in existing]
            write_output(ordered, args.model, leakage_stats(ordered), excluded)
            print(f"  [{index}/{len(todo)}] {len(ordered)} items written", flush=True)

    items = [existing[c] for c in sample_ids if c in existing]
    stats = leakage_stats(items)
    write_output(items, args.model, stats, excluded)

    specific = sum(1 for i in items if i["specific"])
    refusals = sum(1 for r in excluded.values() if r == "refusal")
    print()
    print(f"  items          : {len(items)} of {len(sample_ids)} pinned CVEs")
    print(f"  specific       : {specific} ({specific / max(len(items), 1):.1%})")
    print(f"  excluded       : {len(excluded)} ({refusals} safety refusals, "
          f"{len(excluded) - refusals} other)")
    print(f"  leakage  paraphrased  mean {stats['paraphrased_question']['mean']:.3f} "
          f"median {stats['paraphrased_question']['median']:.3f}")
    print(f"           control      mean {stats['copied_sentence_control']['mean']:.3f} "
          f"median {stats['copied_sentence_control']['median']:.3f}")
    print(f"  wrote {OUTPUT_PATH.relative_to(PROJECT_ROOT)}")


if __name__ == "__main__":
    main()
